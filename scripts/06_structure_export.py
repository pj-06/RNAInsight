"""
RNAInsight - Step 6 : Ligand Structure Export for the Shiny Dashboard
=====================================================================

Purpose
-------
The 14 molecular descriptors used by the models were generated by
``03_descriptor_generation.py`` from each ligand's SMILES string with RDKit.
This script re-opens every unique ligand and exports everything the
dashboard's *Structure Explorer* needs to show HOW each descriptor is
calculated, atom by atom:

* 3D coordinates (ETKDG embedding + MMFF optimisation, explicit hydrogens)
  for the interactive 3D viewer.
* 2D depiction coordinates for the 2D viewer.
* Atom-level / bond-level / ring-level breakdowns for all 14 descriptors
  (which atoms are counted, how much each atom contributes).

Every breakdown is checked against the descriptor value that is stored in
``data/processed/cleaned_dataset.csv``. A molecule whose breakdown does not
reproduce the stored value is reported, so the dashboard never shows an
explanation that disagrees with the data the models were trained on.

Input  : data/processed/cleaned_dataset.csv
Output : dashboard/data/molecules.json
         results/tables/structure_export_check.csv
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from rdkit import Chem, RDLogger
from rdkit.Chem import AllChem, Crippen, Descriptors, rdMolDescriptors
from rdkit.Chem.rdchem import HybridizationType

RDLogger.DisableLog("rdApp.*")

# --------------------------------------------------
# Paths
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent.parent
INPUT_FILE = BASE_DIR / "data" / "processed" / "cleaned_dataset.csv"
OUTPUT_FILE = BASE_DIR / "dashboard" / "data" / "molecules.json"
CHECK_FILE = BASE_DIR / "results" / "tables" / "structure_export_check.csv"

# The 14 descriptors generated in 03_descriptor_generation.py
DESCRIPTORS = [
    "MolecularWeight", "ExactMolWt", "LogP", "MolMR", "TPSA",
    "HBA", "HBD", "RotatableBonds", "RingCount", "NumAromaticRings",
    "NumAliphaticRings", "HeavyAtomCount", "NumHeteroAtoms", "FractionCSP3",
]

# SMARTS definitions used internally by RDKit's C++ descriptor code
# (Code/GraphMol/Descriptors/Lipinski.cpp) for CalcNumHBA, CalcNumHBD and
# the default ("Strict") CalcNumRotatableBonds. Matching them lets us show
# exactly which atoms / bonds were counted; every count is still verified
# against the stored descriptor value.
HBA_SMARTS = Chem.MolFromSmarts(
    "[$([O,S;H1;v2]-[!$(*=[O,N,P,S])]),$([O,S;H0;v2]),$([O,S;-]),"
    "$([N;v3;!$(N-*=!@[O,N,P,S])]),$([nH0X2,o,s;+0])]"
)
HBD_SMARTS = Chem.MolFromSmarts(
    "[N&!H0&v3,N&!H0&+1&v4,O&H1&+0,S&H1&+0,n&H1&+0]"
)
_ROT_ATOM_A = (
    "[!$(*#*)&!D1&!$(C(F)(F)F)&!$(C(Cl)(Cl)Cl)&!$(C(Br)(Br)Br)"
    "&!$(C([CH3])([CH3])[CH3])&!$([CH3])&!$([CD3](=[N,O,S])-!@[#7,O,S!D1])"
    "&!$([#7,O,S!D1]-!@[CD3]=[N,O,S])&!$([CD3](=[N+])-!@[#7!D1])"
    "&!$([#7!D1]-!@[CD3]=[N+])]"
)
_ROT_ATOM_B = (
    "[!$(*#*)&!D1&!$(C(F)(F)F)&!$(C(Cl)(Cl)Cl)&!$(C(Br)(Br)Br)"
    "&!$(C([CH3])([CH3])[CH3])&!$([CH3])]"
)
# The individual alternatives of the acceptor / donor patterns, so the
# dashboard can say WHY each atom was counted.
HBA_RULES = [
    ("[$([O,S;H1;v2]-[!$(*=[O,N,P,S])])]", "OH / SH not attached to C=O, C=N, P=O, S=O"),
    ("[$([O,S;H0;v2])]", "O / S with two bonds and no H (C=O, ether, thioether)"),
    ("[$([O,S;-])]", "negatively charged O / S"),
    ("[$([N;v3;!$(N-*=!@[O,N,P,S])])]", "trivalent N not next to C=O / C=N (amine, imine)"),
    ("[$([nH0X2,o,s;+0])]", "aromatic n without H (pyridine-type), aromatic o / s"),
]
HBD_RULES = [
    ("[N&!H0&v3]", "N-H (amine / amide)"),
    ("[N&!H0&+1&v4]", "protonated N-H+ (ammonium)"),
    ("[O&H1&+0]", "O-H (hydroxyl, acid)"),
    ("[S&H1&+0]", "S-H (thiol)"),
    ("[n&H1&+0]", "aromatic n-H (pyrrole / imidazole type)"),
]
HBA_RULES = [(Chem.MolFromSmarts(sm), why) for sm, why in HBA_RULES]
HBD_RULES = [(Chem.MolFromSmarts(sm), why) for sm, why in HBD_RULES]
ROTATABLE_SMARTS_STRICT = Chem.MolFromSmarts(_ROT_ATOM_A + "-,:;!@" + _ROT_ATOM_B)
ROTATABLE_SMARTS_NONSTRICT = Chem.MolFromSmarts("[!$(*#*)&!D1]-&!@[!$(*#*)&!D1]")

BOND_ORDER = {
    Chem.BondType.SINGLE: 1,
    Chem.BondType.DOUBLE: 2,
    Chem.BondType.TRIPLE: 3,
    Chem.BondType.AROMATIC: 1.5,
}


# --------------------------------------------------
# Geometry
# --------------------------------------------------

def embed_3d(mol: Chem.Mol) -> tuple[Chem.Mol, bool]:
    """Return a hydrogen-complete molecule with 3D coordinates.

    ETKDG embedding is tried with a fixed seed (reproducible), then MMFF
    optimisation (UFF as a fallback). If embedding fails entirely - which
    can happen for large macrocycles - flat 2D coordinates are used so the
    viewer still works, and the flag returned is False.
    """
    mol_h = Chem.AddHs(mol)
    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    status = AllChem.EmbedMolecule(mol_h, params)

    if status != 0:
        params.useRandomCoords = True
        status = AllChem.EmbedMolecule(mol_h, params)

    if status != 0:
        AllChem.Compute2DCoords(mol_h)
        return mol_h, False

    try:
        if AllChem.MMFFHasAllMoleculeParams(mol_h):
            AllChem.MMFFOptimizeMolecule(mol_h, maxIters=500)
        else:
            AllChem.UFFOptimizeMolecule(mol_h, maxIters=500)
    except (ValueError, RuntimeError):
        pass  # keep the unoptimised (still valid) embedding

    return mol_h, True


def coords_of(mol: Chem.Mol, n_atoms: int, digits: int = 3) -> list[list[float]]:
    """Return the first ``n_atoms`` atom positions of the active conformer."""
    conf = mol.GetConformer()
    out = []
    for idx in range(n_atoms):
        pos = conf.GetAtomPosition(idx)
        out.append([round(pos.x, digits), round(pos.y, digits), round(pos.z, digits)])
    return out


# --------------------------------------------------
# Atom-level descriptor breakdowns
# --------------------------------------------------

def fold_h_contribs(mol_h: Chem.Mol, contribs: list[float], n_heavy: int) -> list[float]:
    """Add each explicit hydrogen's contribution onto its heavy-atom parent.

    RDKit's Crippen LogP / MR include hydrogen contributions. Folding them
    onto the parent atom keeps the per-atom picture readable while the
    total stays exactly equal to the descriptor.
    """
    folded = list(contribs[:n_heavy])
    for atom in mol_h.GetAtoms():
        idx = atom.GetIdx()
        if idx < n_heavy:
            continue
        parent = atom.GetNeighbors()[0].GetIdx()
        folded[parent] += contribs[idx]
    return folded


def substructure_atoms(mol: Chem.Mol, pattern: Chem.Mol) -> list[int]:
    """Return sorted unique first-atom indices matched by a SMARTS pattern."""
    return sorted({match[0] for match in mol.GetSubstructMatches(pattern)})


def rule_reasons(mol: Chem.Mol, atoms: list[int], rules: list) -> list[str]:
    """Return, for each counted atom, the first rule (in order) it satisfies."""
    reasons = []
    for idx in atoms:
        why = ""
        for pattern, text in rules:
            if any(match[0] == idx for match in mol.GetSubstructMatches(pattern)):
                why = text
                break
        reasons.append(why)
    return reasons


def rotatable_bonds(mol: Chem.Mol, expected: int) -> list[list[int]]:
    """Return the atom pairs of rotatable bonds, matching RDKit's count.

    RDKit's default definition is "Strict" (amide/ester C-N/C-O bonds,
    CF3 / t-butyl / methyl rotors are not counted). The non-strict variant
    is only used as a fallback if it is the one that reproduces the count.
    """
    for pattern in (ROTATABLE_SMARTS_STRICT, ROTATABLE_SMARTS_NONSTRICT):
        pairs = sorted({tuple(sorted(m)) for m in mol.GetSubstructMatches(pattern)})
        if len(pairs) == expected:
            return [list(p) for p in pairs]
    pairs = sorted({tuple(sorted(m)) for m in mol.GetSubstructMatches(ROTATABLE_SMARTS_STRICT)})
    return [list(p) for p in pairs]


def ring_breakdown(mol: Chem.Mol) -> list[dict]:
    """Describe every SSSR ring: its atoms, size and aromatic/aliphatic type.

    Uses the same rule as RDKit's CalcNumAromaticRings: a ring is aromatic
    only when ALL of its bonds are aromatic, otherwise it is aliphatic.
    """
    ring_info = mol.GetRingInfo()
    rings = []
    for atoms, bonds in zip(ring_info.AtomRings(), ring_info.BondRings()):
        aromatic = all(mol.GetBondWithIdx(b).GetIsAromatic() for b in bonds)
        rings.append({
            "atoms": list(atoms),
            "size": len(atoms),
            "aromatic": aromatic,
        })
    return rings


def describe_molecule(smiles: str) -> dict | None:
    """Build the complete viewer + breakdown record for one SMILES."""
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None

    n_heavy = mol.GetNumAtoms()

    # Crippen contributions are taken from a pristine H-complete copy:
    # MMFF set-up during 3D embedding re-perceives aromaticity in place,
    # which would change the Crippen atom types.
    mol_h_typing = Chem.AddHs(mol)
    mol_h, embedded = embed_3d(mol)

    mol_2d = Chem.Mol(mol)
    AllChem.Compute2DCoords(mol_2d)

    # --- Atoms ------------------------------------------------------------
    # Element / charge / aromaticity / hybridisation come from the original
    # sanitised molecule (the same object the descriptors were computed on).
    atoms = []
    for atom in mol_h_typing.GetAtoms():
        atoms.append({
            "el": atom.GetSymbol(),
            "h": atom.GetTotalNumHs() if atom.GetIdx() < n_heavy else 0,
            "chg": atom.GetFormalCharge(),
            "ar": atom.GetIsAromatic(),
            "hyb": str(atom.GetHybridization()),
        })

    bonds = []
    for bond in mol_h_typing.GetBonds():
        bonds.append([
            bond.GetBeginAtomIdx(),
            bond.GetEndAtomIdx(),
            BOND_ORDER.get(bond.GetBondType(), 1),
        ])

    # --- Mass (average and monoisotopic), per heavy atom incl. its Hs ------
    pt = Chem.GetPeriodicTable()
    h_avg = pt.GetAtomicWeight(1)
    h_mono = pt.GetMostCommonIsotopeMass(1)
    mass_avg, mass_mono = [], []
    for atom in mol.GetAtoms():
        n_h = atom.GetTotalNumHs()
        mass_avg.append(pt.GetAtomicWeight(atom.GetAtomicNum()) + n_h * h_avg)
        mass_mono.append(pt.GetMostCommonIsotopeMass(atom.GetAtomicNum()) + n_h * h_mono)
    # Electron mass correction for charged species (RDKit ExactMolWt does this)
    electron_mass = 0.000548579909065
    charge_corr = -sum(a.GetFormalCharge() for a in mol.GetAtoms()) * electron_mass

    # Element table (count x atomic weight) used for the worked MW example
    element_counts: dict[str, int] = {}
    for atom in mol.GetAtoms():
        element_counts[atom.GetSymbol()] = element_counts.get(atom.GetSymbol(), 0) + 1
    total_h = sum(atom.GetTotalNumHs() for atom in mol.GetAtoms())
    if total_h:
        element_counts["H"] = total_h
    element_table = [
        {
            "el": symbol,
            "n": count,
            "w": round(pt.GetAtomicWeight(symbol), 5),
            "m": round(pt.GetMostCommonIsotopeMass(symbol), 6),
        }
        for symbol, count in sorted(element_counts.items(), key=lambda kv: (kv[0] != "C", kv[0] != "H", kv[0]))
    ]

    # --- Crippen LogP / MR (per atom, H folded onto parents) ---------------
    crippen = rdMolDescriptors._CalcCrippenContribs(mol_h_typing)
    logp_atoms = fold_h_contribs(mol_h_typing, [c[0] for c in crippen], n_heavy)
    mr_atoms = fold_h_contribs(mol_h_typing, [c[1] for c in crippen], n_heavy)

    # --- TPSA (Ertl fragment contributions; N and O only by default) ------
    tpsa_atoms = list(rdMolDescriptors._CalcTPSAContribs(mol))

    # --- Counting descriptors ----------------------------------------------
    hba_atoms = substructure_atoms(mol, HBA_SMARTS)
    hbd_atoms = substructure_atoms(mol, HBD_SMARTS)
    rot_bonds = rotatable_bonds(mol, Descriptors.NumRotatableBonds(mol))
    rings = ring_breakdown(mol)
    hetero_atoms = [a.GetIdx() for a in mol.GetAtoms() if a.GetAtomicNum() not in (1, 6)]
    carbons = [a.GetIdx() for a in mol.GetAtoms() if a.GetAtomicNum() == 6]
    sp3_carbons = [
        a.GetIdx() for a in mol.GetAtoms()
        if a.GetAtomicNum() == 6 and a.GetHybridization() == HybridizationType.SP3
    ]

    breakdown = {
        "mass_avg": [round(v, 4) for v in mass_avg],
        "mass_mono": [round(v, 5) for v in mass_mono],
        "charge_corr": round(charge_corr, 6),
        "elements": element_table,
        "logp": [round(v, 4) for v in logp_atoms],
        "mr": [round(v, 4) for v in mr_atoms],
        "tpsa": [round(v, 3) for v in tpsa_atoms],
        "hba": hba_atoms,
        "hba_why": rule_reasons(mol, hba_atoms, HBA_RULES),
        "hbd": hbd_atoms,
        "hbd_why": rule_reasons(mol, hbd_atoms, HBD_RULES),
        "rot": rot_bonds,
        "rings": rings,
        "hetero": hetero_atoms,
        "carbons": carbons,
        "sp3c": sp3_carbons,
    }

    # Values recomputed from the breakdown (used for verification)
    recomputed = {
        "MolecularWeight": sum(mass_avg),
        "ExactMolWt": sum(mass_mono) + charge_corr,
        "LogP": sum(logp_atoms),
        "MolMR": sum(mr_atoms),
        "TPSA": sum(tpsa_atoms),
        "HBA": len(hba_atoms),
        "HBD": len(hbd_atoms),
        "RotatableBonds": len(rot_bonds),
        "RingCount": len(rings),
        "NumAromaticRings": sum(r["aromatic"] for r in rings),
        "NumAliphaticRings": sum(not r["aromatic"] for r in rings),
        "HeavyAtomCount": n_heavy,
        "NumHeteroAtoms": len(hetero_atoms),
        "FractionCSP3": len(sp3_carbons) / len(carbons) if carbons else 0.0,
    }

    return {
        "smiles": smiles,
        "formula": rdMolDescriptors.CalcMolFormula(mol),
        "n_heavy": n_heavy,
        "embedded3d": embedded,
        "atoms": atoms,
        "bonds": bonds,
        "xyz": coords_of(mol_h, mol_h.GetNumAtoms()),
        "molblock": Chem.MolToMolBlock(mol_h),
        "xy": [c[:2] for c in coords_of(mol_2d, n_heavy)],
        "breakdown": breakdown,
        "recomputed": recomputed,
    }


# --------------------------------------------------
# Main
# --------------------------------------------------

def tolerance_for(name: str) -> float:
    """Allowed absolute difference between stored and recomputed values.

    Stored real-valued descriptors were rounded to 3 decimals in
    03_descriptor_generation.py, so a small tolerance is needed for them.
    """
    return 0.0015 if name in {"MolecularWeight", "ExactMolWt", "LogP", "MolMR", "TPSA", "FractionCSP3"} else 0.0


def main() -> None:
    """Export every unique ligand and verify all 14 descriptor breakdowns."""
    data = pd.read_csv(INPUT_FILE)
    print("Rows loaded:", len(data))

    grouped = data.groupby("SMILES", sort=False)
    print("Unique ligands:", grouped.ngroups)

    molecules = []
    check_rows = []

    for mol_number, (smiles, rows) in enumerate(grouped, start=1):
        record = describe_molecule(smiles)
        if record is None:
            print("  Skipped invalid SMILES:", smiles)
            continue

        first = rows.iloc[0]
        stored = {name: float(first[name]) for name in DESCRIPTORS}

        mismatches = []
        for name in DESCRIPTORS:
            diff = abs(stored[name] - record["recomputed"][name])
            if diff > tolerance_for(name) + 1e-9:
                mismatches.append(f"{name} (stored {stored[name]}, breakdown {record['recomputed'][name]:.4f})")

        check_rows.append({
            "mol_key": mol_number,
            "Name": first["Name"],
            "Verified": not mismatches,
            "Mismatches": "; ".join(mismatches),
        })

        # Per-record info: every dataset row (model row index) of this ligand
        records = [
            {
                "row": int(idx) + 1,  # 1-based row in cleaned/model_ready data
                "family": str(row["Target_Family"]),
                "assay": "" if pd.isna(row["Assay.Target.s."]) else str(row["Assay.Target.s."]).strip(),
                "rbind_id": str(row["X."]),
            }
            for idx, row in rows.iterrows()
        ]

        del record["recomputed"]
        record.update({
            "key": mol_number,
            "name": str(first["Name"]),
            "descriptors": stored,
            "records": records,
            "verified": not mismatches,
        })
        molecules.append(record)

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as handle:
        json.dump(molecules, handle, separators=(",", ":"))

    check = pd.DataFrame(check_rows)
    CHECK_FILE.parent.mkdir(parents=True, exist_ok=True)
    check.to_csv(CHECK_FILE, index=False)

    print("\nLigands exported :", len(molecules))
    print("Fully verified   :", int(check["Verified"].sum()), "/", len(check))
    if not check["Verified"].all():
        print("\nMismatched breakdowns:")
        print(check.loc[~check["Verified"], ["Name", "Mismatches"]].to_string(index=False))
    print("\n3D embedding failures:", sum(not m["embedded3d"] for m in molecules))
    print("Saved:", OUTPUT_FILE)
    print("Saved:", CHECK_FILE)


if __name__ == "__main__":
    main()
